function findInterval(value, intervals) {
    let index = intervals.findIndex(interval => value < interval);
    return index === -1 ? intervals.length - 1 : index;
}

function CalculateRelativeRisk(riskGroupInfo, raceIndex) {
    let beta = beta_[raceIndex-1];
    let betaTotal = riskGroupInfo.reduce((sum, val, i) => sum + val * beta[i], 0);
    let relativeRisk = Math.exp(betaTotal);
    return relativeRisk;
}

function CalculateAbsoluteRisk(jStart, jEnd, relativeRisk, raceIndex) {
    let h2 = h2_[raceIndex-1]; // competing hazards
    let h1_star = h1_star_[raceIndex-1]; // breast cancer hazard
    let PAF = PAF_[raceIndex-1]; // population attributable factor
    let h1 = h1_star.map((value, index) => value * PAF[Math.floor(index / 7)]);

    let prob = 0;

    let s1T = Array(jEnd + 1).fill(1); // survival of competing hazards
    let s2T = Array(jEnd + 1).fill(1); // survival of breast cancer hazard
    for (let i = 1; i <= jEnd; i++) {
        s1T[i] = s1T[i - 1] * Math.exp(-(h1[i - 1] * relativeRisk * 5));
        s2T[i] = s2T[i - 1] * Math.exp(-(h2[i - 1] * 5));
    }

    for (let j = jStart-1; j < jEnd; j++) {
        prob += ((h1[j] * relativeRisk) / (h1[j] * relativeRisk + h2[j])) * (s1T[j] / s1T[jStart-1]) * (s2T[j] / s2T[jStart-1]) * (1.0 - Math.exp(-5 * (h1[j] * relativeRisk + h2[j])));
    }
    return prob * 100;
}
